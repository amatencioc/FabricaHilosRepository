SELECT NUMERO, C_NOMBRE, C.C_COSTO, X.NOMBRE, TRUNC(FECHA) FECHA, TRUNC(F_APROBACION) APROBADO,  
        REPLACE(REQUERIMIENTO,CHR(10),' ') REQUERIMIENTO, REPLACE(SOLUCION,CHR(10),' ') SOLUCION, F_SOLUCION_INI F_INICIO, NVL(S.F_TEST_INI,S.F_SOLUCION) F_TERMINO,S.ESTADO
   FROM CS_SOPCOMP S, CS_TABLAS T, T_CCOSTO C, CENTRO_DE_COSTOS X
   WHERE TIPODOC = 'S'
     AND MOTIVO NOT IN ('11','16')
     AND ((S.ESTADO = '1' AND NVL(S.F_TEST_INI,S.F_SOLUCION) IS NULL) OR (S.ESTADO IN ('2','9') AND NVL(S.F_TEST_INI,S.F_SOLUCION)  BETWEEN '01/01/2026' AND '28/03/2026'))
       AND T.TIPO(+) = '6'
       AND T.CODIGO(+) = S.USER_SOPORTE
       AND C.C_CODIGO = S.C_CODIGO
       AND X.CENTRO_COSTO = C.C_COSTO

SELECT TO_CHAR(S.FECHA, 'MM') MES,
       AVG(ROUND(((NVL(S.F_TEST_INI,S.F_SOLUCION) - S.F_SOLUCION_INI) * 24 * 60),2))  MINUTOS --PARA ATENCION SOPORTE
FROM CS_SOPCOMP S
WHERE TO_CHAR(S.FECHA, 'YYYY') = :P_ANO
  AND S.ESTADO <> '9'
  AND S.MOTIVO NOT IN ('11', '16')
  GROUP BY TO_CHAR(S.FECHA, 'MM')